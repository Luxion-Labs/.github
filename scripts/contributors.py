#!/usr/bin/env python3
"""Rebuild the contributors block in profile/README.md.

Commit counts come from the GitHub API
comes from data/contributors.json.

    python scripts/contributors.py            # update the README
    python scripts/contributors.py --dry-run  # print the block only
    python scripts/contributors.py --offline  # skip the API, use "thanks" only
"""
import argparse
import json
import os
import re
import sys
import urllib.error
import urllib.request
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START = "<!-- CONTRIBUTORS:START -->"
END = "<!-- CONTRIBUTORS:END -->"


def api(path):
    """Yield every item of a paginated GitHub list endpoint."""
    headers = {"Accept": "application/vnd.github+json", "User-Agent": "luxion-contributors"}
    if os.environ.get("GITHUB_TOKEN"):
        headers["Authorization"] = "Bearer " + os.environ["GITHUB_TOKEN"]
    sep = "&" if "?" in path else "?"
    page = 1
    while True:
        req = urllib.request.Request(f"https://api.github.com{path}{sep}per_page=100&page={page}", headers=headers)
        try:
            with urllib.request.urlopen(req, timeout=20) as resp:
                body = resp.read()
        except urllib.error.HTTPError as err:
            if err.code == 409:  # empty repository
                return
            raise
        items = json.loads(body) if body else []
        yield from items
        if len(items) < 100:
            return
        page += 1


def commit_counts(org):
    counts = {}
    for repo in api(f"/orgs/{org}/repos?type=public"):
        if repo["fork"]:
            continue
        for user in api(f"/repos/{org}/{repo['name']}/contributors"):
            if user["type"] == "User":
                counts[user["login"]] = counts.get(user["login"], 0) + user["contributions"]
    return counts


def pick_people(counts, cfg):
    """Return [(login, commits, roles)], most commits first. Credited people always make the cut."""
    thanks = cfg["thanks"]
    people = {u: (n, thanks.get(u, [])) for u, n in counts.items() if u not in cfg["ignore"]}
    for user, roles in thanks.items():
        people.setdefault(user, (0, roles))

    rows = sorted(((u, n, r) for u, (n, r) in people.items()), key=lambda p: (-p[1], p[0].lower()))
    credited = [p for p in rows if p[2]]
    room = max(cfg["limit"] - len(credited), 0)
    fill = {p[0] for p in [p for p in rows if not p[2]][:room]}
    return [p for p in rows if p[2] or p[0] in fill], len(rows)


def render(people, total, cfg):
    cols = cfg["columns"]
    lines = ["<!-- generated by scripts/contributors.py, edit data/contributors.json instead -->"]
    if not people:
        lines.append("Contributors will show up here after the first merged change.")
        return "\n".join(lines)

    lines.append("<table>")
    for i in range(0, len(people), cols):
        lines.append("<tr>")
        for user, commits, roles in people[i:i + cols]:
            u = escape(user)
            notes = [escape(r) for r in roles]
            if commits:
                notes.append(f"{commits} commit" + ("s" if commits != 1 else ""))
            lines.append(
                f'<td align="center" width="{100 // cols}%">'
                f'<a href="https://github.com/{u}"><img src="https://github.com/{u}.png?size=64" width="64" alt="{u}"><br>'
                f'<sub><b>{u}</b></sub></a><br><sub>{", ".join(notes)}</sub></td>'
            )
        lines.append("</tr>")
    lines.append("</table>")

    if total > len(people):
        lines.append(f"\n...and {total - len(people)} more.")
    return "\n".join(lines)


def replace_block(text, block):
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    new, n = pattern.subn(lambda _: f"{START}\n{block}\n{END}", text)
    if n != 1:
        sys.exit(f"profile README needs exactly one {START} ... {END} pair")
    return new


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--offline", action="store_true")
    args = parser.parse_args()

    cfg = json.loads((ROOT / "data" / "contributors.json").read_text(encoding="utf-8"))
    counts = {} if args.offline else commit_counts(cfg["org"])
    people, total = pick_people(counts, cfg)
    block = render(people, total, cfg)

    if args.dry_run:
        print(block)
        return
    readme = ROOT / "profile" / "README.md"
    readme.write_text(replace_block(readme.read_text(encoding="utf-8"), block), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
